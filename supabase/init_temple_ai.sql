-- 1. 宮廟主設定表 (temples)：每一間宮廟只要新增一列
CREATE TABLE IF NOT EXISTS public.temples (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  temple_slug text UNIQUE NOT NULL,        -- 宮廟網址代號 (例如: lungshan, hesheng)
  gothru_url text NOT NULL,                -- GoThru 360 全景網址
  badge_zh text DEFAULT '國定古蹟 • 智慧導覽',
  name_zh text NOT NULL,
  name_en text,
  name_ja text,
  name_ko text,
  intro_zh text,
  intro_en text,
  intro_ja text,
  intro_ko text,
  overview_script_zh text,
  overview_script_en text,
  overview_script_ja text,
  overview_script_ko text,
  address_zh text,
  created_at timestamptz DEFAULT now()
);

-- 2. 360° 全景熱點表 (hotspots)：統一使用 spot_01, spot_02, spot_03 標準代號
CREATE TABLE IF NOT EXISTS public.hotspots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  temple_slug text NOT NULL REFERENCES public.temples(temple_slug) ON DELETE CASCADE,
  spot_id text NOT NULL,                   -- 標準熱點代號 (spot_01, spot_02, spot_03)
  icon text DEFAULT '🦁',
  badge_zh text,
  badge_en text,
  badge_ja text,
  badge_ko text,
  title_zh text NOT NULL,
  title_en text,
  title_ja text,
  title_ko text,
  location_zh text,
  location_en text,
  location_ja text,
  location_ko text,
  content_zh text,
  content_en text,
  content_ja text,
  content_ko text,
  script_zh text,
  script_en text,
  script_ja text,
  script_ko text,
  UNIQUE(temple_slug, spot_id)
);

-- 3. 參拜動線步驟表 (route_steps)
CREATE TABLE IF NOT EXISTS public.route_steps (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  temple_slug text NOT NULL REFERENCES public.temples(temple_slug) ON DELETE CASCADE,
  step_no int NOT NULL,
  name_zh text NOT NULL,
  name_en text,
  name_ja text,
  name_ko text,
  location_zh text,
  location_en text,
  location_ja text,
  location_ko text,
  rule_zh text,
  rule_en text,
  rule_ja text,
  rule_ko text,
  deity_zh text,
  deity_en text,
  deity_ja text,
  deity_ko text,
  desc_zh text,
  desc_en text,
  desc_ja text,
  desc_ko text,
  script_zh text,
  script_en text,
  script_ja text,
  script_ko text,
  UNIQUE(temple_slug, step_no)
);

-- 4. 90% 快取常見問題知識庫表 (knowledge_faqs)
CREATE TABLE IF NOT EXISTS public.knowledge_faqs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  temple_slug text NOT NULL REFERENCES public.temples(temple_slug) ON DELETE CASCADE,
  faq_code text NOT NULL,                  -- 標準代號 (faq_01, faq_02, faq_03, faq_04)
  action_code text,
  category text DEFAULT 'general',
  is_quick_button boolean DEFAULT true,
  keywords text,                           -- 以逗號分隔的觸發關鍵字
  title_zh text NOT NULL,
  title_en text,
  title_ja text,
  title_ko text,
  short_desc_zh text,
  short_desc_en text,
  short_desc_ja text,
  short_desc_ko text,
  content_zh text,
  content_en text,
  content_ja text,
  content_ko text,
  script_zh text,
  script_en text,
  script_ja text,
  script_ko text,
  UNIQUE(temple_slug, faq_code)
);

-- 5. 10% HITL 廟方待審核問題飛輪表 (hitl_pending_questions)
CREATE TABLE IF NOT EXISTS public.hitl_pending_questions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  temple_slug text DEFAULT 'lungshan',
  query text NOT NULL,
  lang text DEFAULT 'zh-TW',
  confidence numeric DEFAULT 0.4,
  reason text,
  suggested_answer text,
  status text DEFAULT 'pending',
  created_at timestamptz DEFAULT now()
);

