ALTER TABLE public.route_steps ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.knowledge_faqs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.hitl_pending_questions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read temples" ON public.temples;
CREATE POLICY "Allow public read temples" ON public.temples FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public read hotspots" ON public.hotspots;
CREATE POLICY "Allow public read hotspots" ON public.hotspots FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public read route_steps" ON public.route_steps;
CREATE POLICY "Allow public read route_steps" ON public.route_steps FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public read knowledge_faqs" ON public.knowledge_faqs;
CREATE POLICY "Allow public read knowledge_faqs" ON public.knowledge_faqs FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public read hitl" ON public.hitl_pending_questions;
CREATE POLICY "Allow public read hitl" ON public.hitl_pending_questions FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert hitl" ON public.hitl_pending_questions;
CREATE POLICY "Allow public insert hitl" ON public.hitl_pending_questions FOR INSERT WITH CHECK (true);

